#!/usr/bin/env python3
"""Build a navigable index of parity catalogs and retained batch reports."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PARITY = ROOT / 'test/parity'
RESULTS = ROOT / 'test/benchmark/results'


def catalog_rows():
    rows = []
    for path in sorted((PARITY / 'catalogs').glob('*.json')):
        catalog = json.loads(path.read_text())
        generator = PARITY / 'catalogs/generators' / ('generate-' + path.stem.rsplit('-', 1)[0] + '.py')
        rows.append((path, len(catalog.get('cases', [])), generator if generator.exists() else None))
    return rows


def batch_rows():
    rows = []
    for manifest_path in sorted(RESULTS.glob('parity-*/manifest.json')):
        manifest = json.loads(manifest_path.read_text())
        cells = manifest.get('cells', [])
        complete = sum((row.get('probe_status'), row.get('operator_peer'), row.get('program_peer')) ==
                       ('correct', 'passed', 'passed') for row in cells)
        rows.append((manifest_path.parent, len(cells), complete))
    return rows


def render():
    lines = ['# Parity artifacts', '', 'Generated by `python3 test/parity/index.py`. Raw evidence stays at its recorded path so existing hashes and ledger links remain valid.', '',
             '## Catalogs', '', '| Catalog | Cells | Generator |', '| --- | ---: | --- |']
    for path, count, generator in catalog_rows():
        catalog_link = path.relative_to(ROOT)
        gen_link = generator.relative_to(ROOT) if generator else None
        lines.append(f'| [{path.name}](../../../{catalog_link}) | {count} | ' +
                     (f'[source](../../../{gen_link})' if gen_link else 'hand maintained') + ' |')
    lines += ['', '## Retained batches', '', '| Batch | Cells | Complete parity |', '| --- | ---: | ---: |']
    for path, count, complete in batch_rows():
        report = path / 'report.md'
        lines.append(f'| [{path.name}]({path.name}/' + ('report.md' if report.exists() else 'manifest.json') + f') | {count} | {complete} |')
    lines += ['', '## Current aggregates', '',
              '- [Coverage outcomes](coverage-outcomes-current-mac-2026-10-29.json)',
              '- [Operator summary](cell-peer-current-summary-mac-2026-10-29.json)',
              '- [Program summary](cell-program-peer-summary-mac-2026-10-29.json)',
              '- [Interactive HTML report](performance-report.html)', '']
    return '\n'.join(lines)


def main():
    output = RESULTS / 'PARITY-INDEX.md'
    output.write_text(render())
    print(output)


if __name__ == '__main__':
    main()
