import { describe, expect, test } from 'std:test'
import checkpoint from 'affon:checkpoint'
import { Session, Tensor, gradient, program, update_parameters } from 'affon:compute'
import { add, argmax, cast, clamp, cross_entropy, div, dot, embedding, eq, exp, gather, gt, index_select, layer_norm, lt, masked_fill, matmul, mean, min, mul, neg, sign, softmax, std, sum, variance, where } from 'affon:ops'
import { sgd } from 'affon:optim'

describe('bf16 and u32 tensor dtypes', () => {
  test('Metal executes bf16 and u32 arithmetic without host fallback', () => {
    const session = new Session({ device: 'metal' })
    const bfLeft = session.tensor([1.00390625, -2.5], { dtype: 'bf16' })
    const bfRight = session.tensor([2, 4], { dtype: 'bf16' })
    const bfSum = add(bfLeft, bfRight)
    expect(bfSum.to_array()).toEqual([3, 1.5])
    const uLeft = session.tensor([0xffffffff, 7], { dtype: 'u32' })
    const uRight = session.tensor([1, 6], { dtype: 'u32' })
    const uSum = add(uLeft, uRight)
    const uProduct = mul(uLeft, uRight)
    expect(uSum.to_array()).toEqual([0, 13])
    expect(uProduct.to_array()).toEqual([0xffffffff, 42])
    uProduct.dispose(); uSum.dispose(); uRight.dispose(); uLeft.dispose()
    bfSum.dispose(); bfRight.dispose(); bfLeft.dispose(); session.dispose()
  })
  test('Metal executes bf16 and u32 unary operations', () => {
    const session = new Session({ device: 'metal' })
    const floats = session.tensor([-1, 0, 1], { dtype: 'bf16' })
    const exponential = exp(floats)
    const limited = clamp(floats, 0, 1)
    expect(exponential.to_array()).toEqual([0.3671875, 1, 2.71875])
    expect(limited.to_array()).toEqual([0, 0, 1])
    const unsigned = session.tensor([0, 1, 0xffffffff], { dtype: 'u32' })
    const negative = neg(unsigned)
    const signs = sign(unsigned)
    expect(negative.to_array()).toEqual([0, 0xffffffff, 1])
    expect(signs.to_array()).toEqual([0, 1, 1])
    signs.dispose(); negative.dispose(); unsigned.dispose()
    limited.dispose(); exponential.dispose(); floats.dispose(); session.dispose()
  })
  test('Metal compares bf16 and u32 values', () => {
    const session = new Session({ device: 'metal' })
    const floats = session.tensor([1, 2, 3], { dtype: 'bf16' })
    const floatBound = session.tensor([2, 2, 2], { dtype: 'bf16' })
    const less = lt(floats, floatBound)
    const equal = eq(floats, floatBound)
    expect(less.to_array()).toEqual([1, 0, 0])
    expect(equal.to_array()).toEqual([0, 1, 0])
    const unsigned = session.tensor([0, 0xffffffff], { dtype: 'u32' })
    const threshold = session.tensor([1, 1], { dtype: 'u32' })
    const greater = gt(unsigned, threshold)
    expect(greater.to_array()).toEqual([0, 1])
    greater.dispose(); threshold.dispose(); unsigned.dispose()
    equal.dispose(); less.dispose(); floatBound.dispose(); floats.dispose(); session.dispose()
  })
  test('Metal selects bf16 and u32 values with broadcast masks', () => {
    const session = new Session({ device: 'metal' })
    const floats = session.tensor([[1, 2], [3, 4]], { dtype: 'bf16' })
    const otherFloats = session.tensor([[5, 6]], { dtype: 'bf16' })
    const floatMask = session.tensor([[1, 0]], { dtype: 'i64' })
    const selectedFloats = where(floatMask, floats, otherFloats)
    const filledFloats = masked_fill(floats, floatMask, 7)
    expect(selectedFloats.to_array()).toEqual([[1, 6], [3, 6]])
    expect(filledFloats.to_array()).toEqual([[7, 2], [7, 4]])
    const unsigned = session.tensor([[1, 2], [3, 4]], { dtype: 'u32' })
    const otherUnsigned = session.tensor([[5, 6]], { dtype: 'u32' })
    const selectedUnsigned = where(floatMask, unsigned, otherUnsigned)
    const filledUnsigned = masked_fill(unsigned, floatMask, 0xffffffff)
    expect(selectedUnsigned.to_array()).toEqual([[1, 6], [3, 6]])
    expect(filledUnsigned.to_array()).toEqual([[0xffffffff, 2], [0xffffffff, 4]])
    filledUnsigned.dispose(); selectedUnsigned.dispose(); otherUnsigned.dispose(); unsigned.dispose()
    filledFloats.dispose(); selectedFloats.dispose(); floatMask.dispose(); otherFloats.dispose(); floats.dispose(); session.dispose()
  })
  test('Metal reads indexed bf16 and u32 values', () => {
    const session = new Session({ device: 'metal' })
    const floats = session.tensor([[1, 2], [3, 4], [5, 6]], { dtype: 'bf16' })
    const rows = session.tensor([2, 0], { dtype: 'i64' })
    const picked = index_select(floats, 0, rows)
    const embedded = embedding(floats, rows)
    expect(picked.to_array()).toEqual([[5, 6], [1, 2]])
    expect(embedded.to_array()).toEqual([[5, 6], [1, 2]])
    const unsigned = session.tensor([[1, 2], [3, 4]], { dtype: 'u32' })
    const columns = session.tensor([[1, 0], [0, 1]], { dtype: 'i64' })
    const gathered = gather(unsigned, 1, columns)
    expect(gathered.to_array()).toEqual([[2, 1], [3, 4]])
    gathered.dispose(); columns.dispose(); unsigned.dispose()
    embedded.dispose(); picked.dispose(); rows.dispose(); floats.dispose(); session.dispose()
  })
  test('Metal casts between bf16, u32, f32, and i64', () => {
    const session = new Session({ device: 'metal' })
    const floats = session.tensor([1, 2.5], { dtype: 'f32' })
    const narrow = cast(floats, 'bf16')
    const wide = cast(narrow, 'f32')
    expect(wide.to_array()).toEqual([1, 2.5])
    const unsigned = session.tensor([0, 0xffffffff], { dtype: 'u32' })
    const signed = cast(unsigned, 'i64')
    expect(signed.to_array()).toEqual([0, 0xffffffff])
    const unsignedAgain = cast(signed, 'u32')
    expect(unsignedAgain.to_array()).toEqual([0, 0xffffffff])
    unsignedAgain.dispose(); signed.dispose(); unsigned.dispose()
    wide.dispose(); narrow.dispose(); floats.dispose(); session.dispose()
  })
  test('Metal casts bf16 and u32 through f64 storage', () => {
    const session = new Session({ device: 'metal' })
    const doubles = session.tensor([1.00390625, 1.01171875, -2.5], { dtype: 'f64' })
    const narrowed = cast(doubles, 'bf16')
    expect(narrowed.to_array()).toEqual([1, 1.015625, -2.5])
    const widened = cast(narrowed, 'f64')
    expect(widened.to_array()).toEqual([1, 1.015625, -2.5])
    const unsigned = session.tensor([0, 0xffffffff], { dtype: 'u32' })
    const asDouble = cast(unsigned, 'f64')
    expect(asDouble.to_array()).toEqual([0, 0xffffffff])
    const again = cast(asDouble, 'u32')
    expect(again.to_array()).toEqual([0, 0xffffffff])
    const outside = session.tensor([4294967296], { dtype: 'f64' })
    expect(() => cast(outside, 'u32')).toThrow()
    outside.dispose()
    again.dispose(); asDouble.dispose(); unsigned.dispose()
    widened.dispose(); narrowed.dispose(); doubles.dispose(); session.dispose()
  })
  test('Metal reduces bf16 and u32 tensors', () => {
    const session = new Session({ device: 'metal' })
    const floats = session.tensor([[1, 2], [3, 4]], { dtype: 'bf16' })
    const total = sum(floats)
    const means = mean(floats, 1)
    const variances = variance(floats, 1)
    const deviations = std(floats, 1)
    expect(total.to_array()).toEqual([10])
    expect(means.to_array()).toEqual([1.5, 3.5])
    expect(variances.to_array()).toEqual([0.25, 0.25])
    expect(deviations.to_array()).toEqual([0.5, 0.5])
    const unsigned = session.tensor([[4, 1], [2, 3]], { dtype: 'u32' })
    const minima = min(unsigned, 1)
    const indices = argmax(unsigned, 1)
    const unsignedMean = mean(unsigned, 1)
    const unsignedVariance = variance(unsigned, 1)
    const bestFloat = argmax(floats)
    expect(minima.to_array()).toEqual([1, 2])
    expect(indices.to_array()).toEqual([0, 1])
    expect(unsignedMean.to_array()).toEqual([2, 2])
    expect(unsignedVariance.to_array()).toEqual([2, 0])
    expect(bestFloat.to_array()).toEqual([3])
    bestFloat.dispose(); unsignedVariance.dispose(); unsignedMean.dispose()
    indices.dispose(); minima.dispose(); unsigned.dispose()
    deviations.dispose(); variances.dispose(); means.dispose(); total.dispose(); floats.dispose(); session.dispose()
  })
  test('Metal computes bf16 softmax and normalization', () => {
    const session = new Session({ device: 'metal' })
    const zeros = session.tensor([[0, 0], [0, 0]], { dtype: 'bf16' })
    const probabilities = softmax(zeros, 1)
    expect(probabilities.to_array()).toEqual([[0.5, 0.5], [0.5, 0.5]])
    const values = session.tensor([[1, 3]], { dtype: 'bf16' })
    const normalized = layer_norm(values, 1, 1)
    expect(normalized.to_array()).toEqual([[-0.70703125, 0.70703125]])
    normalized.dispose(); values.dispose(); probabilities.dispose(); zeros.dispose(); session.dispose()
  })
  test('Metal computes bf16 cross entropy', () => {
    const session = new Session({ device: 'metal' })
    const logits = session.tensor([[0, 0]], { dtype: 'bf16' })
    const targets = session.tensor([0], { dtype: 'i64' })
    const loss = cross_entropy(logits, targets)
    expect(Math.abs(loss.item() - Math.log(2)) < 0.005).toBe(true)
    loss.dispose(); targets.dispose(); logits.dispose(); session.dispose()
  })
  test('Metal computes bf16 and u32 matrix products', () => {
    const session = new Session({ device: 'metal' })
    const left = session.tensor([[1, 2]], { dtype: 'bf16' })
    const right = session.tensor([[3], [4]], { dtype: 'bf16' })
    const result = matmul(left, right)
    expect(result.to_array()).toEqual([[11]])
    const unsignedLeft = session.tensor([[0xffffffff, 2]], { dtype: 'u32' })
    const unsignedRight = session.tensor([[2], [3]], { dtype: 'u32' })
    const unsignedResult = matmul(unsignedLeft, unsignedRight)
    expect(unsignedResult.to_array()).toEqual([[4]])
    const batchedLeft = session.tensor([[[1, 2]], [[3, 4]]], { dtype: 'bf16' })
    const batchedRight = session.tensor([[[2], [3]]], { dtype: 'bf16' })
    const batchedResult = matmul(batchedLeft, batchedRight)
    expect(batchedResult.to_array()).toEqual([[[8]], [[18]]])
    const dotLeft = session.tensor([1, 2], { dtype: 'bf16' })
    const dotRight = session.tensor([3, 4], { dtype: 'bf16' })
    const dotResult = dot(dotLeft, dotRight)
    expect(dotResult.item()).toBe(11)
    const unsignedDotLeft = session.tensor([0xffffffff, 2], { dtype: 'u32' })
    const unsignedDotRight = session.tensor([2, 3], { dtype: 'u32' })
    const unsignedDot = dot(unsignedDotLeft, unsignedDotRight)
    expect(unsignedDot.item()).toBe(4)
    unsignedDot.dispose(); unsignedDotRight.dispose(); unsignedDotLeft.dispose()
    dotResult.dispose(); dotRight.dispose(); dotLeft.dispose()
    batchedResult.dispose(); batchedRight.dispose(); batchedLeft.dispose()
    unsignedResult.dispose(); unsignedRight.dispose(); unsignedLeft.dispose(); result.dispose()
    right.dispose(); left.dispose(); session.dispose()
  })
  test('Metal divides u32 values and reports a zero divisor', () => {
    const session = new Session({ device: 'metal' })
    const left = session.tensor([7, 8], { dtype: 'u32' })
    const right = session.tensor([2, 3], { dtype: 'u32' })
    const result = div(left, right)
    expect(result.to_array()).toEqual([3, 2])
    const zero = session.tensor([1, 0], { dtype: 'u32' })
    expect(() => div(left, zero)).toThrow()
    zero.dispose(); result.dispose(); right.dispose(); left.dispose(); session.dispose()
  })
  test('bf16 rounds to nearest even and computes with bf16 storage', () => {
    const session = new Session({ device: 'cpu' })
    const first = session.tensor([1.00390625, 1.01171875, -2.5], { dtype: 'bf16' })
    expect(first.dtype).toBe('bf16')
    expect(first.to_array()).toEqual([1, 1.015625, -2.5])
    const second = session.tensor([2, 3, 4], { dtype: 'bf16' })
    const sum = add(first, second)
    expect(sum.dtype).toBe('bf16')
    expect(sum.to_array()).toEqual([3, 4, 1.5])
    const widened = cast(first, 'f32')
    expect(widened.to_array()).toEqual([1, 1.015625, -2.5])
    widened.dispose(); sum.dispose(); second.dispose(); first.dispose(); session.dispose()
  })

  test('bf16 matrix multiplication accumulates before rounding', () => {
    const session = new Session({ device: 'cpu' })
    const left = session.tensor([[1, 2]], { dtype: 'bf16' })
    const right = session.tensor([[3], [4]], { dtype: 'bf16' })
    const result = matmul(left, right)
    expect(result.dtype).toBe('bf16')
    expect(result.to_array()).toEqual([[11]])
    result.dispose(); right.dispose(); left.dispose(); session.dispose()
  })

  test('u32 validates its range and executes arithmetic', () => {
    const session = new Session({ device: 'cpu' })
    expect(() => session.tensor([-1], { dtype: 'u32' })).toThrow('u32')
    expect(() => session.tensor([0x100000000], { dtype: 'u32' })).toThrow('u32')
    expect(() => session.tensor([1.5], { dtype: 'u32' })).toThrow('u32')
    const left = session.tensor([0xffffffff, 7], { dtype: 'u32' })
    const right = session.tensor([1, 6], { dtype: 'u32' })
    const sum = add(left, right)
    const product = mul(left, right)
    expect(sum.dtype).toBe('u32')
    expect(sum.to_array()).toEqual([0, 13])
    expect(product.to_array()).toEqual([0xffffffff, 42])
    const widened = cast(left, 'i64')
    expect(widened.to_array()).toEqual([0xffffffff, 7])
    widened.dispose(); product.dispose(); sum.dispose(); right.dispose(); left.dispose(); session.dispose()
  })

  test('formal specifications preserve the new dtypes', () => {
    const source = program('new_dtype_specs', p => [
      p.argument('float', Tensor.bf16([2])),
      p.argument('unsigned', Tensor.u32([2])),
    ])
    expect(source.inspect().arguments.map(value => value.spec.dtype)).toEqual(['bf16', 'u32'])
  })

  test('new dtypes execute through a Metal session', () => {
    const session = new Session({ device: 'metal' })
    const floats = session.tensor([1, 2], { dtype: 'bf16' })
    const integers = session.tensor([4, 5], { dtype: 'u32' })
    const floatSum = add(floats, floats)
    const integerSum = add(integers, integers)
    expect(floatSum.to_array()).toEqual([2, 4])
    expect(integerSum.to_array()).toEqual([8, 10])
    integerSum.dispose(); floatSum.dispose(); integers.dispose(); floats.dispose(); session.dispose()
  })

  test('checkpoint round trips bf16 and u32 storage', () => {
    const path = `/tmp/affon-new-dtypes-${Date.now()}-${Math.floor(Math.random() * 1e6)}.safetensors`
    const session = new Session({ device: 'cpu' })
    const bf16 = session.tensor([1.01171875, -2.5], { dtype: 'bf16' })
    const u32 = session.tensor([0, 0xffffffff], { dtype: 'u32' })
    checkpoint.save({ bf16, u32 }, path)
    expect(checkpoint.inspect(path)).toEqual({ bf16: { dtype: 'BF16', shape: [2] }, u32: { dtype: 'U32', shape: [2] } })
    const loaded = checkpoint.load(path) as any
    expect(loaded.bf16.dtype).toBe('bf16')
    expect(loaded.bf16.to_array()).toEqual([1.015625, -2.5])
    expect(loaded.u32.dtype).toBe('u32')
    expect(loaded.u32.to_array()).toEqual([0, 0xffffffff])
    loaded.bf16.dispose(); loaded.u32.dispose(); bf16.dispose(); u32.dispose(); session.dispose()
  })

  test('bf16 parameters can be differentiated', () => {
    const model = program('bf16_gradient', p => mean(mul(
      p.argument('x', Tensor.bf16([2])),
      p.parameter('weight', Tensor.bf16([2])),
    )))
    const derivative = gradient(model, 'weight')
    const session = new Session({ device: 'cpu' })
    const state = session.initialize(derivative, { parameters: { weight: [1, 1] } })
    const input = session.tensor([2, 4], { dtype: 'bf16' })
    const result = session.compile(derivative).run({ x: input }, state) as any
    expect(result.dtype).toBe('bf16')
    expect(result.to_array()).toEqual([1, 2])
    result.dispose(); input.dispose(); state.dispose(); session.dispose()
  })

  test('bf16 parameters can take an SGD step', () => {
    const model = program('bf16_sgd', p => mean(mul(
      p.argument('x', Tensor.bf16([2])),
      p.parameter('weight', Tensor.bf16([2])),
    )))
    const update = update_parameters(model, gradient(model, 'weight'), sgd({ learning_rate: 0.25 }))
    const session = new Session({ device: 'cpu' })
    const state = session.initialize(update, { parameters: { weight: [1, 1] } })
    const input = session.tensor([2, 4], { dtype: 'bf16' })
    const result = session.compile(update).run({ x: input }, state) as any
    expect(result.item()).toBe(3)
    expect(state.parameters['bf16_sgd.weight'].to_array()).toEqual([0.75, 0.5])
    result.dispose(); input.dispose(); state.dispose(); session.dispose()
  })
})
